export const getTimezoneCode = (date: Date, timeZone: string): string => {
  try {
    const parts = new Intl.DateTimeFormat('en-US', {
      timeZone,
      timeZoneName: 'short'
    }).formatToParts(date);
    return parts.find(p => p.type === 'timeZoneName')?.value || timeZone;
  } catch {
    return timeZone;
  }
};

export const getFormattedTimezones = (): TimezoneOption[] => {
  let timezones: string[];
  try {
    timezones = (Intl as unknown as { supportedValuesOf: (key: string) => string[] }).supportedValuesOf('timeZone');
  } catch {
    timezones = [
      'UTC',
      'America/New_York',
      'America/Chicago',
      'America/Denver',
      'America/Phoenix',
      'America/Los_Angeles',
      'America/Vancouver',
      'Europe/London',
      'Europe/Paris',
      'Asia/Kolkata',
      'Asia/Singapore',
      'Asia/Tokyo',
      'Australia/Sydney'
    ];
  }

  const uniqueTzs = Array.from(new Set(timezones)).sort();
  const date = new Date();
  
  return uniqueTzs.map(tz => {
    const code = getTimezoneCode(date, tz);
    return {
      value: tz,
      label: `${tz} (${code})`
    };
  });
};

export const getTimezonesForCountry = (countryName: string): TimezoneOption[] => {
  if (!countryName) return getFormattedTimezones();
  return COUNTRY_TIMEZONE_MAP[countryName] || getFormattedTimezones();
};
